export type StudyLevelId = 'iniciante' | 'intermediario' | 'avancado';

export type SignCategory =
  | 'alfabeto'
  | 'numeros'
  | 'cores'
  | 'cumprimentos'
  | 'familia'
  | 'verbos'
  | 'perguntas'
  | 'saude'
  | 'trabalho'
  | 'expressoes';

export type FacialMood = 'neutral' | 'smile' | 'question' | 'emphasis' | 'concerned';

export type MotionType =
  | 'static'
  | 'wave-lateral'
  | 'forward-arc'
  | 'chin-forward'
  | 'tap-double'
  | 'circle'
  | 'nod-wrist'
  | 'shake-side'
  | 'point-self'
  | 'point-other'
  | 'heart-circle'
  | 'up-down';

export interface HandPoseKey {
  /** Finger curl from 0 (fully extended) to 1 (fully curled into palm): [thumb, index, middle, ring, pinky] */
  fingers: [number, number, number, number, number];
  /** Finger spread factor 0 (closed together) to 1 (wide open) */
  spread: number;
  /** Wrist rotation in degrees (-60 to 60) */
  wristAngle: number;
  /** Palm orientation */
  palm: 'front' | 'side' | 'back' | 'inward' | 'up' | 'down';
  /** Target arm anchor relative to torso center: x (-1..1), y (-1..1 where -0.6 is forehead, -0.2 chin, 0.2 chest) */
  anchor: { x: number; y: number };
  /** Motion pattern applied to the hand */
  motion: MotionType;
  /** Optional second hand mirror/support */
  twoHands?: boolean;
  /** Facial non-manual expression */
  facial: FacialMood;
}

export interface LibrasSign {
  id: string;
  word: string;
  gloss: string;
  aliases?: string[];
  category: SignCategory;
  level: StudyLevelId;
  handshape: string;
  location: string;
  movement: string;
  facialExpression: string;
  description: string;
  culturalNote: string;
  isAlphabet?: boolean;
  pose: HandPoseKey;
}

export interface QuizQuestion {
  id: string;
  type: 'identify' | 'gloss-order' | 'articulation';
  prompt: string;
  targetSignId?: string;
  options: string[];
  correctAnswer: string;
  explanation: string;
}

